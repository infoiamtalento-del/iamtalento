const mkTabs = (
  pageId: string,
  baseRoute: string,
  labels: string[]
): AdminMenuTab[] =>
  labels.map((label, idx) => {
    const slug = label
      .toLowerCase()
      .replace(/&/g, "and")
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "");
    return {
      id: `${pageId}.${String(idx + 1).padStart(2, "0")}`,
      label,
      slug,
      route: `${baseRoute}?tab=${slug}`,
    };
  });

