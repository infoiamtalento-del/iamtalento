export interface ResolvedMenuPage {
  group: AdminMenuGroup;
  module: AdminMenuModule;
  page: AdminMenuPage;
}

const PAGE_INDEX: Record<string, ResolvedMenuPage> = {};
for (const group of SUPER_ADMIN_MENU_GROUPS) {
  for (const mod of group.modules) {
    for (const page of mod.pages) {
      PAGE_INDEX[page.id] = { group, module: mod, page };
    }
  }
}

export function findMenuPageById(pageId: string): ResolvedMenuPage {
  return PAGE_INDEX[pageId] || PAGE_INDEX["01.01"];
}

